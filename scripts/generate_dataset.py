"""Generate deterministic, licence-safe TraceMark evaluation images."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

SEED = 20260720


def gradient(width: int, height: int, dark: bool = False) -> Image.Image:
    x = np.linspace(0, 1, width, dtype=np.float32)
    y = np.linspace(0, 1, height, dtype=np.float32)[:, None]
    red = np.broadcast_to((x * 180 + (10 if dark else 50))[None, :], (height, width))
    green = np.broadcast_to(y * 170 + (5 if dark else 60), (height, width))
    blue = (1 - x[None, :]) * 120 + y * 80 + (5 if dark else 35)
    return Image.fromarray(np.clip(np.dstack((red, green, blue)), 0, 255).astype(np.uint8), "RGB")


def texture(width: int, height: int, rng: np.random.Generator) -> Image.Image:
    yy, xx = np.indices((height, width))
    checker = ((xx // 24 + yy // 24) % 2) * 90
    waves = 50 * np.sin(xx / 11) + 35 * np.cos(yy / 17)
    noise = rng.normal(0, 24, (height, width))
    base = np.clip(100 + checker + waves + noise, 0, 255)
    rgb = np.dstack((base, np.roll(base, 19, axis=1), np.roll(base, 31, axis=0)))
    return Image.fromarray(rgb.astype(np.uint8), "RGB")


def edges_and_text(width: int, height: int, bright: bool = True) -> Image.Image:
    background = (240, 244, 248) if bright else (16, 25, 39)
    foreground = (14, 55, 78) if bright else (226, 235, 241)
    image = Image.new("RGB", (width, height), background)
    draw = ImageDraw.Draw(image)
    font = ImageFont.load_default()
    for index in range(10):
        inset = 18 + index * 14
        draw.rectangle((inset, inset, width - inset, height - inset), outline=foreground, width=3)
    for row in range(8):
        draw.text((48, 50 + row * 42), f"TRACEMARK FORENSIC FIXTURE {row + 1:02}", fill=foreground, font=font)
    draw.polygon(
        [(width * 0.62, height * 0.2), (width * 0.9, height * 0.5), (width * 0.62, height * 0.8)],
        outline=foreground,
        width=6,
    )
    return image


def alpha_fixture(width: int, height: int) -> Image.Image:
    image = gradient(width, height).convert("RGBA")
    alpha = np.linspace(40, 255, width, dtype=np.uint8)
    image.putalpha(Image.fromarray(np.broadcast_to(alpha, (height, width)).copy(), "L"))
    return image


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path("datasets/generated"))
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)

    fixtures = {
        "landscape-gradient.png": gradient(1024, 640),
        "portrait-text.png": edges_and_text(640, 1024),
        "square-texture.png": texture(768, 768, rng),
        "landscape-edges.webp": edges_and_text(960, 600),
        "dark-gradient.jpg": gradient(900, 600, dark=True),
        "alpha-gradient.png": alpha_fixture(768, 640),
    }

    manifest: list[dict[str, object]] = []
    for filename, image in fixtures.items():
        path = output / filename
        if path.suffix == ".jpg":
            image.save(path, quality=94, subsampling=0)
        elif path.suffix == ".webp":
            image.save(path, quality=92)
        else:
            image.save(path)
        manifest.append(
            {
                "filename": filename,
                "width": image.width,
                "height": image.height,
                "mode": image.mode,
                "role": "clean-and-negative-control",
                "provenance": "Generated by scripts/generate_dataset.py; CC0 project fixture",
                "seed": SEED,
            }
        )

    (output / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Generated {len(fixtures)} fixtures in {output}")


if __name__ == "__main__":
    main()
